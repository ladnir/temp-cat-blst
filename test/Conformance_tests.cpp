unsigned char hex_nibble(char c)
{
    if (c >= '0' && c <= '9') {
        return static_cast<unsigned char>(c - '0');
    }
    if (c >= 'a' && c <= 'f') {
        return static_cast<unsigned char>(c - 'a' + 10);
    }
    return 0xff;
}

void expect_hex(const unsigned char* actual, size_t actual_size, const char* expected)
{
    ASSERT_EQ(std::strlen(expected), actual_size * 2);
    std::ostringstream actual_hex;
    actual_hex << std::hex << std::setfill('0');
    for (size_t i = 0; i < actual_size; ++i) {
        const unsigned char hi = hex_nibble(expected[2 * i]);
        const unsigned char lo = hex_nibble(expected[2 * i + 1]);
        ASSERT_LE(hi, 0x0f);
        ASSERT_LE(lo, 0x0f);
        actual_hex << std::setw(2) << static_cast<unsigned int>(actual[i]);
    }
    EXPECT_EQ(actual_hex.str(), expected);
}

template<size_t N>
std::array<unsigned char, N> decode_hex(const char* encoded)
{
    std::array<unsigned char, N> out = {};
    EXPECT_EQ(std::strlen(encoded), N * 2);
    for (size_t i = 0; i < N; ++i) {
        const unsigned char hi = hex_nibble(encoded[2 * i]);
        const unsigned char lo = hex_nibble(encoded[2 * i + 1]);
        EXPECT_LE(hi, 0x0f);
        EXPECT_LE(lo, 0x0f);
        out[i] = static_cast<unsigned char>((hi << 4) | lo);
    }
    return out;
}

blst_fp12 draft_pairing_vector()
{
    blst_fp12 raw = {};
    size_t chunk = 0;
    for (size_t fp6_component = 0; fp6_component < 3; ++fp6_component) {
        for (size_t fp12_component = 0; fp12_component < 2;
             ++fp12_component) {
            for (size_t fp2_component = 0; fp2_component < 2;
                 ++fp2_component) {
                const std::array<unsigned char, 48> coefficient =
                    decode_hex<48>(kGtOutputChunks[chunk++]);
                blst_fp_from_bendian(
                    &raw.fp6[fp12_component]
                         .fp2[fp6_component]
                         .fp[fp2_component],
                    coefficient.data());
            }
        }
    }
    return raw;
}

void expect_production_pairing_matches_draft(const blst_fp12& pairing)
{
    const blst_fp12 raw = draft_pairing_vector();

    // Appendix B.1 specifies e_lib(P,Q) = e_pseudocode(P,Q)^k for production
    // libraries and k=3 for BLS12-381. Verify that convention explicitly so
    // the draft bytes are not incorrectly compared to BLST's production GT.
    blst_fp12 raw_squared = {};
    blst_fp12 expected = {};
    blst_fp12_sqr(&raw_squared, &raw);
    blst_fp12_mul(&expected, &raw_squared, &raw);
    EXPECT_TRUE(blst_fp12_is_equal(&pairing, &expected));

    std::array<unsigned char, 12 * 48> serialized = {};
    blst_bendian_from_fp12(serialized.data(), &raw);
    for (size_t i = 0; i < 12; ++i) {
        SCOPED_TRACE("draft Fp12 coefficient " + std::to_string(i));
        expect_hex(serialized.data() + i * 48, 48, kGtOutputChunks[i]);
    }
}

TEST(Conformance, PairingFriendlyCurvesDraft13Scalar)
{
    std::array<unsigned char, 48> g1 = {};
    std::array<unsigned char, 96> g2 = {};
    blst_p1_compress(g1.data(), blst_p1_generator());
    blst_p2_compress(g2.data(), blst_p2_generator());
    expect_hex(g1.data(), g1.size(), kG1Compressed);
    expect_hex(g2.data(), g2.size(), kG2Compressed);

    blst_fp12 miller = {};
    blst_fp12 pairing = {};
    blst_miller_loop(
        &miller, blst_p2_affine_generator(), blst_p1_affine_generator());
    blst_final_exp(&pairing, &miller);
    expect_production_pairing_matches_draft(pairing);
}

TEST(Conformance, PairingFriendlyCurvesDraft13Avx)
{
    if (!blst_avx_enabled()) {
        GTEST_SKIP() << "AVX production path is unavailable in this build.";
    }

    const blst_avx_p1* g1_generator = blst_avx_p1_generator();
    const blst_avx_p2* g2_generator = blst_avx_p2_generator();
    ASSERT_NE(g1_generator, nullptr);
    ASSERT_NE(g2_generator, nullptr);

    std::array<unsigned char, 48> g1 = {};
    std::array<unsigned char, 96> g2 = {};
    ASSERT_TRUE(blst_avx_p1_compress(g1.data(), g1_generator));
    ASSERT_TRUE(blst_avx_p2_compress(g2.data(), g2_generator));
    expect_hex(g1.data(), g1.size(), kG1Compressed);
    expect_hex(g2.data(), g2.size(), kG2Compressed);

    blst_avx_fp12 avx_pairing = {};
    blst_fp12 scalar_layout = {};
    ASSERT_TRUE(blst_avx_pairing(&avx_pairing, g1_generator, g2_generator));
    ASSERT_TRUE(blst_fp12_from_avx(&scalar_layout, &avx_pairing));
    expect_production_pairing_matches_draft(scalar_layout);
}

TEST(Conformance, BlsDraft07BasicSignatureVectors)
{
    const std::array<unsigned char, 20> sk_bytes =
        decode_hex<20>(kReferenceSecretKey);
    const unsigned char message[] = {'s', 'a', 'm', 'p', 'l', 'e'};
    const unsigned char g1_dst[] =
        "BLS_SIG_BLS12381G1_XMD:SHA-256_SSWU_RO_NUL_";
    const unsigned char g2_dst[] =
        "BLS_SIG_BLS12381G2_XMD:SHA-256_SSWU_RO_NUL_";

    blst_scalar sk = {};
    ASSERT_TRUE(blst_scalar_from_be_bytes(
        &sk, sk_bytes.data(), sk_bytes.size()));

    blst_p1 g1_hash = {};
    blst_p1 g1_signature = {};
    blst_p2 g2_public_key = {};
    blst_hash_to_g1(
        &g1_hash,
        message,
        sizeof(message),
        g1_dst,
        sizeof(g1_dst) - 1,
        nullptr,
        0);
    blst_sign_pk_in_g2(&g1_signature, &g1_hash, &sk);
    blst_sk_to_pk_in_g2(&g2_public_key, &sk);

    std::array<unsigned char, 48> g1_compressed = {};
    blst_p1_compress(g1_compressed.data(), &g1_signature);
    expect_hex(
        g1_compressed.data(), g1_compressed.size(), kReferenceG1Signature);

    blst_p1_affine g1_signature_affine = {};
    blst_p2_affine g2_public_key_affine = {};
    blst_p1_to_affine(&g1_signature_affine, &g1_signature);
    blst_p2_to_affine(&g2_public_key_affine, &g2_public_key);
    EXPECT_EQ(
        blst_core_verify_pk_in_g2(
            &g2_public_key_affine,
            &g1_signature_affine,
            true,
            message,
            sizeof(message),
            g1_dst,
            sizeof(g1_dst) - 1,
            nullptr,
            0),
        BLST_SUCCESS);

    blst_p2 g2_hash = {};
    blst_p2 g2_signature = {};
    blst_p1 g1_public_key = {};
    blst_hash_to_g2(
        &g2_hash,
        message,
        sizeof(message),
        g2_dst,
        sizeof(g2_dst) - 1,
        nullptr,
        0);
    blst_sign_pk_in_g1(&g2_signature, &g2_hash, &sk);
    blst_sk_to_pk_in_g1(&g1_public_key, &sk);

    std::array<unsigned char, 96> g2_compressed = {};
    blst_p2_compress(g2_compressed.data(), &g2_signature);
    expect_hex(
        g2_compressed.data(), g2_compressed.size(), kReferenceG2Signature);

    blst_p2_affine g2_signature_affine = {};
    blst_p1_affine g1_public_key_affine = {};
    blst_p2_to_affine(&g2_signature_affine, &g2_signature);
    blst_p1_to_affine(&g1_public_key_affine, &g1_public_key);
    EXPECT_EQ(
        blst_core_verify_pk_in_g1(
            &g1_public_key_affine,
            &g2_signature_affine,
            true,
            message,
            sizeof(message),
            g2_dst,
            sizeof(g2_dst) - 1,
            nullptr,
            0),
        BLST_SUCCESS);
}

