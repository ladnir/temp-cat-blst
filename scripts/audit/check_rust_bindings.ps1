[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$cHeaderPath = Join-Path $repoRoot 'bindings\blst_scalar.h'
$rustBindingsPath = Join-Path $repoRoot 'bindings\rust\src\bindings.rs'
$generatorPath = Join-Path $repoRoot 'build\generate-rust-bindings.sh'
$trimPath = Join-Path $repoRoot 'build\bindings_trim.pl'
$errors = [System.Collections.Generic.List[string]]::new()

function Read-Text([string]$Path)
{
    return [System.IO.File]::ReadAllText($Path)
}

$cHeader = Read-Text $cHeaderPath
$cHeader = [regex]::Replace($cHeader, '(?s)/\*.*?\*/', '')
$cHeader = [regex]::Replace($cHeader, '(?m)//.*$', '')
$cPattern = '(?ms)^\s*(?:BLST_[A-Z_]+\s+)*' +
    '[A-Za-z_][A-Za-z0-9_\s\*]*?\b(blst_[A-Za-z0-9_]+)' +
    '\s*\([^;]*?\)\s*;'
$cSymbols = @(
    [regex]::Matches($cHeader, $cPattern) |
        ForEach-Object { $_.Groups[1].Value } |
        Sort-Object -Unique
)

$rustBindings = Read-Text $rustBindingsPath
$rustPattern = '(?m)^\s*pub fn\s+(blst_[A-Za-z0-9_]+)\s*\('
$rustSymbols = @(
    [regex]::Matches($rustBindings, $rustPattern) |
        ForEach-Object { $_.Groups[1].Value } |
        Sort-Object -Unique
)

$missing = @(Compare-Object $cSymbols $rustSymbols |
    Where-Object SideIndicator -eq '<=' |
    ForEach-Object InputObject)
$extra = @(Compare-Object $cSymbols $rustSymbols |
    Where-Object SideIndicator -eq '=>' |
    ForEach-Object InputObject)
if ($missing.Count -ne 0)
{
    $errors.Add("Raw Rust bindings are missing scalar C symbols: $($missing -join ', ')")
}
if ($extra.Count -ne 0)
{
    $errors.Add("Raw Rust bindings contain non-scalar symbols: $($extra -join ', ')")
}
if ($cSymbols.Count -ne 259 -or $rustSymbols.Count -ne 259)
{
    $errors.Add(
        "Expected exact 259/259 scalar declaration inventory; found " +
        "$($cSymbols.Count)/$($rustSymbols.Count)."
    )
}

foreach ($splitSymbol in @(
    'blst_fr_fft_domain_len',
    'blst_fr_fft_domain_init',
    'blst_fr_fft_with_domain'
))
{
    if ($rustSymbols -contains $splitSymbol)
    {
        $errors.Add("Split FFT declaration leaked into generated bindings: $splitSymbol")
    }
}
if ($rustSymbols -notcontains 'blst_pairing_alignof')
{
    $errors.Add('Generated bindings omit blst_pairing_alignof.')
}

if ($rustBindings -notmatch '^/\* automatically generated by rust-bindgen 0\.65\.1 \*/')
{
    $errors.Add('Generated binding does not record rust-bindgen 0.65.1.')
}
foreach ($resultType in @('BLST_ERROR', 'BLST_UNIQ_RESULT'))
{
    if ($rustBindings -notmatch "(?s)#\[repr\(transparent\)\].*?pub struct $resultType\(pub u32\);")
    {
        $errors.Add("$resultType is not a forward-safe transparent u32 newtype.")
    }
    if ($rustBindings -match "pub enum $resultType")
    {
        $errors.Add("$resultType regressed to a closed Rust enum.")
    }
}
foreach ($layoutTest in @(
    'bindgen_test_layout_blst_error',
    'bindgen_test_layout_blst_uniq_result'
))
{
    if ($rustBindings -notmatch "(?m)^fn $layoutTest\(\)")
    {
        $errors.Add("Generated bindings omit result-layout regression: $layoutTest")
    }
}
foreach ($opaqueType in @('pairing', 'uniq'))
{
    $contextType = "blst_${opaqueType}_context"
    if ($rustBindings -notmatch "(?s)#\[repr\(C\)\]\s*#\[derive\(Debug\)\]\s*pub struct $contextType\s*\{\s*_unused: \[u8; 0\],\s*\}\s*pub type blst_$opaqueType = $contextType;")
    {
        $errors.Add("Generated bindings do not preserve the distinct opaque $contextType tag and C alias.")
    }
}
if ($rustBindings -notmatch '(?s)#\[repr\(C\)\]\s*#\[derive\(Debug\)\]\s*pub struct blst_scalar_prepared_g2_batch\s*\{\s*_unused: \[u8; 0\],\s*\}')
{
    $errors.Add('Generated bindings do not preserve the opaque scalar prepared-G2 batch tag.')
}
if ($rustBindings -match '(?m)^pub const _STDINT_H\b' -or
    $rustBindings -match '(?m)^pub type __u_char\b' -or
    $rustBindings -match '::core::os::raw::')
{
    $errors.Add('Generated bindings leaked implementation details from system headers.')
}

$generator = Read-Text $generatorPath
if ($generator -notmatch 'BINDGEN_VERSION=0\.65\.1')
{
    $errors.Add('Generator does not require rust-bindgen 0.65.1.')
}
if ($generator -notmatch "--newtype-enum 'BLST\.\*'")
{
    $errors.Add('Generator does not emit BLST result enums as newtypes.')
}
if ($generator -notmatch "RUSTFMT_VERSION='rustfmt 1\.5\.1-stable \(897e375 2022-11-02\)'")
{
    $errors.Add('Generator does not require the pinned Rust 1.65 formatter.')
}
if ($generator -notmatch '--formatter none')
{
    $errors.Add('Generator does not isolate bindgen from its ambient formatter.')
}
if ($generator -notmatch '--config-path "\$BINDINGS/rust/rustfmt\.toml"')
{
    $errors.Add('Generator does not pin the repository rustfmt configuration.')
}
if ($generator -notmatch "--allowlist-function '\^blst_\.\*'")
{
    $errors.Add('Generator does not restrict functions to the public blst_ C API.')
}
if ($generator -notmatch "--allowlist-type '\^\(blst_\.\*\|BLST_\.\*\)'")
{
    $errors.Add('Generator does not restrict types to public BLST names.')
}
if ($generator -notmatch "--blocklist-type '\^blst_\.\*_must_be_4_bytes\$'")
{
    $errors.Add('Generator does not exclude C-only enum-size assertion typedefs.')
}
if ($generator -match '--opaque-type\s+blst_(?:pairing|uniq)')
{
    $errors.Add('Generator erases a distinct opaque C context tag.')
}
if ($generator -match '--rustified-enum')
{
    $errors.Add('Generator still permits closed rustified C result enums.')
}
if ($generator -notmatch 'blst_scalar\.h -- -std=c99 "-I\$HERE/\.\."')
{
    $errors.Add('Generator input is not the scalar C99 header with the repository include root.')
}
if ($generator -match '(?m)^\s*blst\.h\s+--')
{
    $errors.Add('Generator consumes the compatibility umbrella header.')
}

$trim = Read-Text $trimPath
foreach ($required in @('use strict;', 'use warnings;', 'require_rewrite',
                         'expected exactly one', '%expected'))
{
    if (-not $trim.Contains($required))
    {
        $errors.Add("Binding postprocessor lacks fail-closed marker: $required")
    }
}

if ($errors.Count -ne 0)
{
    foreach ($errorMessage in $errors)
    {
        Write-Error $errorMessage
    }
    throw "Rust binding integrity check failed with $($errors.Count) error(s)."
}

Write-Host (
    "Rust binding integrity passed: {0} scalar C declarations, {1} raw Rust declarations." -f
    $cSymbols.Count, $rustSymbols.Count
)
